-- Create MedUI's read-only login and attach it to the restored databases.
-- The password comes from the READER_PASSWORD environment variable (sqlcmd reads env vars as $(...)), never the command line.
:on error exit
IF SUSER_ID('$(READER_USER)') IS NULL
    CREATE LOGIN [$(READER_USER)] WITH PASSWORD = '$(READER_PASSWORD)', CHECK_POLICY = OFF, DEFAULT_DATABASE = BPSPATIENTS;
GO
USE BPSPATIENTS;       IF USER_ID('$(READER_USER)') IS NULL CREATE USER [$(READER_USER)] FOR LOGIN [$(READER_USER)]; ELSE ALTER USER [$(READER_USER)] WITH LOGIN = [$(READER_USER)]; ALTER ROLE db_datareader ADD MEMBER [$(READER_USER)];
GO
USE BPSDocuments1;     IF USER_ID('$(READER_USER)') IS NULL CREATE USER [$(READER_USER)] FOR LOGIN [$(READER_USER)]; ELSE ALTER USER [$(READER_USER)] WITH LOGIN = [$(READER_USER)]; ALTER ROLE db_datareader ADD MEMBER [$(READER_USER)];
GO
USE BPSDOCUMENTSINBOX; IF USER_ID('$(READER_USER)') IS NULL CREATE USER [$(READER_USER)] FOR LOGIN [$(READER_USER)]; ELSE ALTER USER [$(READER_USER)] WITH LOGIN = [$(READER_USER)]; ALTER ROLE db_datareader ADD MEMBER [$(READER_USER)];
GO
